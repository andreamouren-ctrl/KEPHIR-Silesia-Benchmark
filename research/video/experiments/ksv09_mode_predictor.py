#!/usr/bin/env python3
"""
KSV-09 cheap MC residual-mode predictor.

Goal:
- retain TEMP vs MC backend comparison;
- avoid running KHEPRI on both MC_MOD8 and MC_ZZ_INTER;
- choose the MC residual representation from cheap statistics.

Three predictors are tested:
  P1 SIGNED_MAG  : prefer ZZ when modulo residuals concentrate near zero signed magnitude.
  P2 EDGE_WRAP   : signed magnitude plus penalty for wrap-heavy symbols near 128.
  P3 LOCAL_MATCH : signed magnitude plus short-distance equality score after mapping.

These are project heuristics, not novelty claims.
"""
import argparse, hashlib, json, math, shutil, subprocess, tempfile, time
from pathlib import Path

from kstream_video_motion_control import motion_residual
from kstream_video_residual_symbols_v7 import zz_byte
from kstream_video_baseline import frame_sizes, split_frame

W=176; H=144; BLOCK=8; RADIUS=4; FS=W*H*3//2

def sha(p): return hashlib.sha256(Path(p).read_bytes()).hexdigest()

def residual_stats(raw_chunk,w,h,block=8,radius=4):
    ys,cs,_,_=frame_sizes(w,h); fs=ys+2*cs
    frames=[raw_chunk[i:i+fs] for i in range(0,len(raw_chunk),fs)]
    vals=[]
    prev=None
    for frame in frames:
        if prev is not None:
            _,res=motion_residual(frame,prev,w,h,block,radius)
            vals.extend(res)
        prev=frame
    if not vals:
        return {"count":0,"mean_signed_mag":0.0,"wrap_frac":0.0,"local_mod":0.0,"local_zz":0.0}
    n=len(vals)
    sm=sum((b if b<128 else 256-b) for b in vals)/n
    wrap=sum(1 for b in vals if 96<=b<=160)/n
    zz=[zz_byte(b) for b in vals]
    def eqscore(a):
        if len(a)<17:return 0.0
        hits=0; total=0
        for d in (1,2,4,8,16):
            total+=len(a)-d
            hits+=sum(1 for i in range(d,len(a)) if a[i]==a[i-d])
        return hits/total if total else 0.0
    return {"count":n,"mean_signed_mag":sm,"wrap_frac":wrap,
            "local_mod":eqscore(vals),"local_zz":eqscore(zz)}

def choose(stats,predictor):
    sm=stats["mean_signed_mag"]; wrap=stats["wrap_frac"]
    if predictor=="P1":
        return "ZZ" if sm<15.0 else "MOD8"
    if predictor=="P2":
        score=sm + 20.0*wrap
        return "ZZ" if score<22.0 else "MOD8"
    if predictor=="P3":
        # prefer ZZ only when residual magnitude is modest and mapping does not
        # materially reduce short-distance equality.
        gain=stats["local_zz"]-stats["local_mod"]
        return "ZZ" if (sm<22.0 and gain>-0.0025) else "MOD8"
    raise ValueError("bad predictor")

def main():
    ap=argparse.ArgumentParser()
    ap.add_argument("--samples-json",type=Path,required=True,
                    help="JSON generated by KSV-09 collector")
    a=ap.parse_args()
    data=json.loads(a.samples_json.read_text())
    out={}
    for pred in ("P1","P2","P3"):
        correct=0; regret=0; decisions=[]
        for s in data["windows"]:
            pick=choose(s["stats"],pred)
            oracle=s["oracle_mc_mode"]
            correct+=pick==oracle
            chosen=s["mc_zz_bytes"] if pick=="ZZ" else s["mc_mod8_bytes"]
            best=min(s["mc_zz_bytes"],s["mc_mod8_bytes"])
            regret+=chosen-best
            decisions.append({"clip":s["clip"],"window":s["window"],"pick":pick,"oracle":oracle,
                              "regret_bytes":chosen-best})
        out[pred]={"correct":correct,"total":len(data["windows"]),
                   "accuracy":correct/len(data["windows"]) if data["windows"] else 0.0,
                   "mc_regret_bytes":regret,"decisions":decisions}
    print(json.dumps(out,indent=2))

if __name__=="__main__":main()
